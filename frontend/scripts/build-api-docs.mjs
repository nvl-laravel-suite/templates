import ts from 'typescript'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const config = ts.readConfigFile(path.join(root, 'tsconfig.json'), ts.sys.readFile)
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root)
const program = ts.createProgram(parsed.fileNames, parsed.options)
const checker = program.getTypeChecker()
const escape = (text) => text.replaceAll('|', '&#124;').replace(/\s+/g, ' ').trim()
const compare = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
const lines = [
  '# Public export inventory',
  '',
  '<!-- Generated by scripts/build-api-docs.mjs. Edit the source exports and run npm run build:docs. -->',
  '',
  'Every JavaScript entry point and named TypeScript export is listed below. The declarations linked for each symbol contain its complete signature and nested types. Declarations are generated by `npm run build:package` and are included in the installed package.',
  '',
  'For behavior and examples, start with the [documentation map](README.md), [template API](TEMPLATE_API.md), [voucher API](API.md), and [command reference](COMMANDS.md). Values ending in `Schema` are runtime validators; a type-only import has no JavaScript runtime value.',
  '',
]
let count = 0
for (const [subpath, entry] of Object.entries(pkg.exports)) {
  if (typeof entry !== 'object' || !entry.import) continue
  const name = subpath === '.' ? 'index' : subpath.slice(2)
  const source = program.getSourceFile(path.join(root, `src/${name}.ts`))
  if (!source) throw new Error(`Missing source entry: ${name}`)
  const module = checker.getSymbolAtLocation(source)
  const exports = checker
    .getExportsOfModule(module)
    .map((symbol) => {
      const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
      const declarations = symbol.getDeclarations() ?? []
      const typeOnly = declarations.some(
        (node) => ts.isExportSpecifier(node) && (node.isTypeOnly || node.parent.parent.isTypeOnly),
      )
      const value = !typeOnly && Boolean(target.flags & ts.SymbolFlags.Value)
      const kind = !value
        ? 'Type'
        : target.flags & ts.SymbolFlags.Class
          ? 'Class'
          : target.flags & ts.SymbolFlags.Function
            ? 'Function'
            : symbol.name.endsWith('Schema')
              ? 'Schema'
              : 'Value'
      const declaration = target.getDeclarations()?.find((node) =>
        node
          .getSourceFile()
          .fileName.replaceAll('\\', '/')
          .toLowerCase()
          .startsWith(path.join(root, 'src').replaceAll('\\', '/').toLowerCase() + '/'),
      )
      const filename = declaration
        ? path
            .relative(path.join(root, 'src'), declaration.getSourceFile().fileName)
            .replaceAll('\\', '/')
            .replace(/\.tsx?$/, '.d.ts')
        : `${name}.d.ts`
      const description = ts.displayPartsToString(target.getDocumentationComment(checker)).split('\n')[0]
      const deprecated = target.getJsDocTags().find((tag) => tag.name === 'deprecated')
      return {
        name: symbol.name,
        kind,
        filename,
        description: deprecated
          ? 'Deprecated: ' + ts.displayPartsToString(deprecated.text ?? [])
          : description,
      }
    })
    .sort(compare)
  count += exports.length
  lines.push(
    `## ${pkg.name}${subpath === '.' ? '' : subpath.slice(1)}`,
    '',
    `${exports.length} named exports. [Entry declarations](../dist/types/${name}.d.ts).`,
    '',
    '| Export | Kind | Declaration / description |',
    '|---|---|---|',
  )
  for (const item of exports)
    lines.push(
      `| \`${item.name}\` | ${item.kind} | [Declaration](../dist/types/${item.filename})${item.description ? ' · ' + escape(item.description) : ''} |`,
    )
  lines.push('')
}
const eventSource = await readFile(path.join(root, 'src/voucher-builder/store/events.ts'), 'utf8')
const eventUnion = eventSource.slice(
  eventSource.indexOf('export type BuilderActionEvent ='),
  eventSource.indexOf('export type BuilderActionType'),
)
lines.push(
  '## Voucher action events',
  '',
  'Complete event payload union. Subscribe through onAction, useVoucherEvent(type, handler), or instance.subscribeAction(handler). Selection and operation events are included; payloads are isolated snapshots delivered after committed batches.',
  '',
  '```ts',
  eventUnion.trim(),
  '```',
  '',
)
lines.push(
  '## Non-JavaScript assets',
  '',
  '| Export | Purpose |',
  '|---|---|',
  '| `/styles.css` | Browser workspace and document styles; import once in the host app. |',
  '| `/schemas/*` | Five generated Draft 2020-12 JSON Schemas. |',
  '| `/package.json` | Package metadata and export map. |',
  '',
  'Runtime internals are excluded from this inventory unless a public entry explicitly exports them. Deep imports into `dist` are implementation details. Prefer the named entry points above.',
  '',
)
const output = lines.join('\n')
const target = path.join(root, 'docs/PUBLIC_API.md')
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== output) throw new Error('Public export inventory is stale. Run npm run build:docs.')
  console.log(`Public API inventory matches ${count} export listings across ten entries.`)
} else {
  await writeFile(target, output)
  console.log(`Documented ${count} export listings across ten entries.`)
}
